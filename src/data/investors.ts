export const investorById = (id: string) => INVESTORS.find((i) => i.id === id);

/**
 * Kenya track record — DERIVED from the tracked rounds feed (ecosystem.ts).
 * A round matches an investor when the investor is a named lead (or named in
 * the round note) or the company sits in the verified portfolio. Nothing here
 * is invented: it is a projection of ROUNDS + portfolio claims.
 */
export function investorRounds(id: string): { led: RoundItem[]; context: RoundItem[] } {
  const inv = investorById(id);
  if (!inv) return { led: [], context: [] };
  const aliases: Record<string, string[]> = {
    tlcom: ['tlcom'],
    blueorchard: ['blueorchard', 'insuresilience'],
    waterequity: ['waterequity'],
    renew: ['renew'],
    havaic: ['havaic'],
    delta40: ['delta40'],
    antler: ['antler'],
    flourish: ['flourish'],
    villgro: [],
    dob: ['dob equity'],
    chandaria: ['chandaria'],
    spark: ['spark', 'safaricom'],
    shakavc: ['shaka'],
    globalventures: ['global ventures'],
    invhestia: [],
    risefund: ['rise fund', 'tpg'],
    tigerglobal: ['tiger global'],
    softbank: ['softbank'],
    africinvest: ['africinvest'],
  };
  const keys = aliases[id] ?? [id];
  const led = ROUNDS.filter((r) => {
    const hay = `${r.lead} ${r.note ?? ''}`.toLowerCase();
    return keys.some((k) => hay.includes(k));
  });
  const context = ROUNDS.filter(
    (r) => inv.portfolio.includes(r.companyId) && !led.includes(r)
  );
  return { led, context };
}
